#!/usr/bin/env node
/**
 * Emit the supervisor runner's JavaScript dependency closure.
 *
 * Node refuses to strip types for a `.ts` file under `node_modules`
 * (`ERR_UNSUPPORTED_NODE_MODULES_TYPE_STRIPPING`), so the executable that ships
 * cannot be the TypeScript source. This script transpiles the runner and every
 * module it imports at runtime into flat `.mjs` files under `generated/`, with
 * relative specifiers rewritten to the emitted names and type-only imports
 * erased.
 *
 * The closure is checked in so the package works without a build step, and
 * `supervisor.codegen.test.ts` regenerates it and fails on drift. Run it after
 * changing the runner or its runtime dependencies:
 *
 * ```
 * node src/supervisor/emit-runner.mjs            # writes generated/
 * node src/supervisor/emit-runner.mjs <outDir>   # writes elsewhere (drift test)
 * ```
 *
 * Bare imports are limited to `node:` builtins on purpose: the closure must run
 * from a bare install without relying on the caller's module graph.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ts = require("typescript");

const here = dirname(fileURLToPath(import.meta.url));
const outputDir = process.argv[2] ? resolve(process.argv[2]) : join(here, "generated");

/** Runtime entry first; everything else is reachable from it. */
const CLOSURE = [
  { source: join(here, "runner.ts"), out: "runner.mjs" },
  { source: join(here, "store.ts"), out: "store.mjs" },
  { source: join(here, "types.ts"), out: "types.mjs" },
  { source: join(here, "identity.ts"), out: "identity.mjs" },
  { source: join(here, "..", "conditions.ts"), out: "conditions.mjs" },
  { source: join(here, "..", "process.ts"), out: "process.mjs" },
  { source: join(here, "..", "process-identity.ts"), out: "process-identity.mjs" },
];

const bySource = new Map(CLOSURE.map((entry) => [resolve(entry.source), entry.out]));

const COMPILER_OPTIONS = {
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  isolatedModules: true,
  removeComments: false,
  newLine: ts.NewLineKind.LineFeed,
};

const BANNER = "// Generated by src/supervisor/emit-runner.mjs from the TypeScript source.\n"
  + "// Do not edit: change the source and re-run the emitter (a drift test enforces this).\n";

function rewriteSpecifiers(code, sourcePath) {
  const sourceDir = dirname(sourcePath);
  const replace = (match, prefix, specifier, suffix) => {
    const target = bySource.get(resolve(sourceDir, specifier));
    if (!target) {
      throw new Error(
        `${relative(here, sourcePath)} imports ${JSON.stringify(specifier)}, which is not part of the emitted runner closure. `
          + "Add it to CLOSURE in emit-runner.mjs or remove the runtime import.",
      );
    }
    return `${prefix}./${target}${suffix}`;
  };
  const rewritten = code.replace(/(from\s*")((?:\.\.?\/)[^"]*\.ts)(")/g, replace);
  const dynamicRewritten = rewritten.replace(/(import\s*\(\s*")((?:\.\.?\/)[^"]*\.ts)(")/g, replace);
  const leftover = dynamicRewritten.match(/(?:from\s*"|import\s*\(\s*")((?:\.\.?\/)[^"]*\.ts)"/);
  if (leftover) {
    throw new Error(`${relative(here, sourcePath)} still references ${leftover[1]} after emission.`);
  }
  return dynamicRewritten;
}

mkdirSync(outputDir, { recursive: true });
const emitted = [];
for (const entry of CLOSURE) {
  const source = readFileSync(entry.source, "utf8");
  const result = ts.transpileModule(source, {
    fileName: entry.source,
    compilerOptions: COMPILER_OPTIONS,
    reportDiagnostics: true,
  });
  const errors = (result.diagnostics ?? []).filter((diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error);
  if (errors.length > 0) {
    const messages = errors.map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n"));
    throw new Error(`Could not emit ${entry.out}: ${messages.join("; ")}`);
  }
  const code = rewriteSpecifiers(result.outputText, entry.source);
  writeFileSync(join(outputDir, entry.out), `${BANNER}\n${code}`);
  emitted.push(entry.out);
}

process.stdout.write(`emitted ${emitted.length} module(s) to ${outputDir}: ${emitted.join(", ")}\n`);
