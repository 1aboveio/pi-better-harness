#!/usr/bin/env node
/**
 * Emit the standalone coordinator executable and its JavaScript dependency
 * closure.
 *
 * Node refuses type stripping under `node_modules`, so a detached coordinator
 * cannot be started from `.ts` in an installed package. This mirrors
 * `src/supervisor/emit-runner.mjs`: transpile every runtime module into flat
 * ESM under `generated/`, rewrite relative specifiers, and check the result in.
 *
 * ```
 * node src/coordinator/emit-runner.mjs            # writes generated/
 * node src/coordinator/emit-runner.mjs <outDir>   # drift test
 * ```
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ts = require("typescript");

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, "..", "..");
const outputDir = process.argv[2] ? resolve(process.argv[2]) : join(here, "generated");

const coordinator = (name) => join(here, name);
const source = (path) => join(packageRoot, "src", path);
const sharedRoot = join(packageRoot, "src", "shared-operation-coordinator");

const CLOSURE = [
  { source: coordinator("runner.ts"), out: "coordinator.mjs" },
  { source: coordinator("server.ts"), out: "server.mjs" },
  { source: coordinator("protocol.ts"), out: "protocol.mjs" },
  { source: coordinator("paths.ts"), out: "paths.mjs" },
  { source: coordinator("retention.ts"), out: "retention.mjs" },
  { source: source("maintenance-core.ts"), out: "maintenance-core.mjs" },
  { source: source("registry.ts"), out: "registry.mjs" },
  { source: source("types.ts"), out: "background-types.mjs" },
  { source: source("process-identity.ts"), out: "process-identity.mjs" },
  { source: source("process.ts"), out: "process.mjs" },
  { source: source("conditions.ts"), out: "conditions.mjs" },
  { source: source("supervisor/index.ts"), out: "supervisor-index.mjs" },
  { source: source("supervisor/supervisor.ts"), out: "supervisor.mjs" },
  { source: source("supervisor/store.ts"), out: "supervisor-store.mjs" },
  { source: source("supervisor/types.ts"), out: "supervisor-types.mjs" },
  { source: source("supervisor/identity.ts"), out: "identity.mjs" },
  { source: source("supervisor/invocation.ts"), out: "invocation.mjs" },
  { source: join(sharedRoot, "index.ts"), out: "oc-index.mjs" },
];

for (const name of readdirSync(join(sharedRoot, "src"))) {
  if (!name.endsWith(".ts") || name.endsWith(".test.ts")) continue;
  CLOSURE.push({ source: join(sharedRoot, "src", name), out: `oc-${name.replace(/\.ts$/, ".mjs")}` });
}

const bySource = new Map(CLOSURE.map((entry) => [resolve(entry.source), entry.out]));

const COMPILER_OPTIONS = {
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  isolatedModules: true,
  // Comments sometimes contain example import paths; emit without them so the
  // closure check cannot mistake documentation for a runtime dependency.
  removeComments: true,
  newLine: ts.NewLineKind.LineFeed,
};

const BANNER = "// Generated by src/coordinator/emit-runner.mjs from the TypeScript source.\n"
  + "// Do not edit: change the source and re-run the emitter (a drift test enforces this).\n";

function targetFor(sourcePath, specifier) {
  const candidate = resolve(dirname(sourcePath), specifier);
  return bySource.get(candidate)
    ?? bySource.get(candidate.replace(/\.js$/, ".ts"))
    ?? bySource.get(candidate.replace(/\.mjs$/, ".ts"));
}

function rewriteSpecifiers(code, sourcePath) {
  const replace = (match, prefix, specifier, suffix) => {
    const target = targetFor(sourcePath, specifier);
    if (!target) {
      throw new Error(
        `${relative(packageRoot, sourcePath)} imports ${JSON.stringify(specifier)}, which is not part of the emitted coordinator closure. `
          + "Add it to CLOSURE in emit-runner.mjs or make it type-only.",
      );
    }
    return `${prefix}./${target}${suffix}`;
  };
  const rewritten = code
    .replace(/(from\s*")((?:\.\.?\/)[^"]+\.(?:ts|js|mjs))(")/g, replace)
    .replace(/(import\s*\(\s*")((?:\.\.?\/)[^"]+\.(?:ts|js|mjs))(")/g, replace);
  const leftover = rewritten.match(/(?:from\s*"|import\s*\(\s*")((?:\.\.?\/)[^"]+\.(?:ts|js))"/);
  if (leftover) throw new Error(`${relative(packageRoot, sourcePath)} still references ${leftover[1]} after emission.`);
  return rewritten;
}

mkdirSync(outputDir, { recursive: true });
const emitted = [];
for (const entry of CLOSURE) {
  const text = readFileSync(entry.source, "utf8");
  const result = ts.transpileModule(text, {
    fileName: entry.source,
    compilerOptions: COMPILER_OPTIONS,
    reportDiagnostics: true,
  });
  const errors = (result.diagnostics ?? []).filter((diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error);
  if (errors.length > 0) {
    const messages = errors.map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n"));
    throw new Error(`Could not emit ${entry.out}: ${messages.join("; ")}`);
  }
  const code = rewriteSpecifiers(result.outputText, entry.source);
  writeFileSync(join(outputDir, entry.out), `${BANNER}\n${code}`);
  emitted.push(entry.out);
}

process.stdout.write(`emitted ${emitted.length} module(s) to ${outputDir}: ${emitted.join(", ")}\n`);
