/** Select a saved, installed worker closure without changing the server owner. */
import { readFileSync, realpathSync, statSync } from "node:fs";
import { basename, dirname, join, normalize, sep } from "node:path";

const DOMAIN = join("src", "runtime", "domain", "subagents");
type Recipe = { runtimeRoot?: string; baseExtensionArgs?: readonly string[]; extensionArgs?: readonly string[] };
type Command = { file: string; fileArgs: string[] };

export function managedRuntimeRoot(domain: string): string | undefined {
    if (!domain.endsWith(`${sep}${DOMAIN}`)) return undefined;
    const root = domain.slice(0, -(DOMAIN.length + 1));
    return basename(dirname(root)) === "releases" && /^[a-f0-9]{64}$/.test(basename(root)) ? root : undefined;
}

export interface ContinuationRuntime {
    root: string;
    mapPath(path: string): string;
    mapArgs(args: readonly string[]): string[];
    command(command: Command): Command;
}

/**
 * Only sibling, published releases are eligible. User extensions retain their
 * original identity check. Permission policy is still generated by the current
 * server; a saved runtime does not grandfather its previous permission grants.
 * Published releases are retained by the installer (it removes staging only).
 * Any future release GC must treat LaunchRecipe.runtimeRoot as a reference.
 */
export function selectContinuationRuntime(options: { currentDir: string; recipe?: Recipe }): ContinuationRuntime | undefined {
    const current = managedRuntimeRoot(options.currentDir);
    if (!current || !options.recipe) return undefined;
    const recipe = options.recipe;
    // Upgrade recipes written before runtimeRoot existed using the mandatory
    // harness control, never a user-selected/custom extension path.
    const args = recipe.baseExtensionArgs ?? recipe.extensionArgs ?? [];
    const steer = args.find((value, index) => args[index - 1] === "--extension" && value.endsWith(`${sep}${DOMAIN}${sep}child-steer.ts`));
    const saved = recipe.runtimeRoot ?? (steer ? managedRuntimeRoot(dirname(steer)) : undefined);
    if (!saved || saved === current) return undefined;
    const unavailable = (detail: string): never => {
        throw new Error(`Cannot resume: saved runtime ${basename(saved)} unavailable (${detail}). Restore that release or explicitly launch a replacement conversation; no worker was started.`);
    };
    if (normalize(saved) !== saved || dirname(saved) !== dirname(current) || !/^[a-f0-9]{64}$/.test(basename(saved))) {
        return unavailable("not a sibling managed release");
    }
    function manifest(root: string) {
        let value;
        try {
            if (realpathSync(root) !== root) return unavailable("release path is not canonical");
            value = JSON.parse(readFileSync(join(root, "runtime.json"), "utf8"));
        } catch { return unavailable("missing or unreadable release manifest"); }
        if (value.format !== 1 || value.root !== root || value.build?.contentId !== basename(root)
            || value.node !== join(root, "node/bin/node") || value.installRoot !== dirname(dirname(root))) {
            return unavailable("invalid release manifest");
        }
        return value;
    }
    const before = manifest(saved), now = manifest(current);
    // These releases share the existing v1 worker admission/policy/bridge wire
    // formats. Refuse SDK, Node, platform or protocol transitions rather than
    // assuming that a new server can host any historic worker.
    if (before.build.protocolVersion !== 1 || now.build.protocolVersion !== 1
        || ["piSdkVersion", "nodeVersion", "platform"].some(key => !before.build[key] || before.build[key] !== now.build[key])) {
        throw new Error(`Cannot resume: saved runtime ${basename(saved)} is incompatible with the current worker protocol, SDK or platform. Explicit replacement is required; no worker was started.`);
    }
    function required(path: string, directory = false): string {
        try {
            const stat = statSync(path);
            if (realpathSync(path) !== path || !(stat.isFile() || directory && stat.isDirectory())) return unavailable("worker file is missing or redirected");
        } catch { return unavailable("worker file is missing or unreadable"); }
        return path;
    }
    const node = required(before.node);
    const mapPath = (path: string): string => path.startsWith(`${current}${sep}`)
        ? required(join(saved, path.slice(current.length + 1)), true) : path;
    return {
        root: saved,
        mapPath,
        mapArgs: values => values.map((value, index) => values[index - 1] === "--extension" ? mapPath(value) : value),
        command: command => {
            // Only executable slots are rewritten. A prompt or arbitrary CLI
            // value that happens to contain a runtime path must stay untouched.
            const fileArgs = [...command.fileArgs];
            fileArgs[0] = mapPath(fileArgs[0]!);
            if (basename(fileArgs[0]!) === "task-runtime.mjs") fileArgs[1] = mapPath(fileArgs[1]!);
            return { file: node, fileArgs };
        },
    };
}
